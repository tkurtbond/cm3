#!/bin/sh
# Generate ASCII M3CG IR dumps for a set of m3tests programs.
#
# Usage: LLVM-IR-backend-docs/gen_m3cg_corpus.sh WORKDIR [OUTDIR] [TEST...]
#   WORKDIR  scratch directory (e.g. /usr/local/sw/tmp/<you>/corpus); it is
#            emptied and reused.
#   OUTDIR   where to put the dumps (default: LLVM-IR-backend-docs/m3cg-corpus).
#   TEST     m3tests directories relative to m3-sys/m3tests/src, e.g. p0/p036
#            (default: the list below).
#
# Why not "cm3 -keep"?  In C mode -keep is supposed to tee the binary IR to
# Foo.mc / Foo.ic (Builder.m3 PushOneM3 sets m3env.sideIRName), but
# RunM3Front -> ResetEnv clears env.sideIRName before the code generator is
# opened, so nothing is written.  And USE_C_BACKEND_VIA_M3CGCAT is dead too:
# m3cgcat's C output is commented out.  So instead we build in
# ExternalObject mode, where cm3 always writes the .mc/.ic IR file and calls
# the quake proc m3_backend, and we redefine m3_backend to dump the IR as
# ASCII.  Linking then fails (there are no objects); that is expected.
#
# Requires: the m3tests support library built in-tree
# (cd m3-sys/m3tests && cm3), and cm3 + m3cgcat on PATH.

set -eu
ROOT=$(cd "$(dirname "$0")/.." && pwd)
TESTSRC=$ROOT/m3-sys/m3tests/src
W=${1:?usage: $0 WORKDIR [OUTDIR] [TEST...]}
OUT=${2:-$ROOT/LLVM-IR-backend-docs/m3cg-corpus}
[ $# -ge 2 ] && shift 2 || shift $#
TESTS=${*:-"c0/c001 c0/c008 c0/c014 p0/p029 p0/p036 p0/p042 p0/p053 p0/p057 p0/p061 p0/p066 p0/p073"}

rm -rf "$W"
mkdir -p "$W/src" "$OUT"

cat > "$W/src/Corpus.common" <<EOF
% Generated by gen_m3cg_corpus.sh: dump M3CG IR instead of compiling it.
proc m3_backend (source, object, optimize, debug) is
  return try_exec ("m3cgcat", "-in-binary:" & source, "-out-ascii:" & source & ".txt")
end
import ("libm3")
override ("m3tests", "$ROOT/m3-sys")
import ("m3tests")
program ("pgm")
EOF

for t in $TESTS; do
  d=$W/src/$t
  mkdir -p "$d"
  cp "$TESTSRC/$t"/*.[im]3 "$d"/
  sed 's|include *( *"../../Test.common" *)|include ("../../Corpus.common")|' \
    "$TESTSRC/$t/m3makefile" > "$d/m3makefile"
  (cd "$d" && cm3 -DM3_BACKEND_MODE=ExternalObject > build.log 2>&1) || true
  o=$OUT/$(echo "$t" | tr / -)
  rm -rf "$o"
  mkdir -p "$o"
  cp "$TESTSRC/$t"/*.[im]3 "$o"/
  n=0
  for f in "$d"/AMD64_LINUX/*.[im]c.txt; do
    [ -e "$f" ] || continue
    cp "$f" "$o"/
    n=$((n + 1))
  done
  echo "$t: $n IR files"
  [ $n -gt 0 ] || { echo "  no IR; see $d/build.log"; tail -5 "$d/build.log"; }
done
